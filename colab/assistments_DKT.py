def run_python(*arguments, log_name=None):
    """Stream progress; close the log before checksumming or archiving it."""
    log = (RUN_ROOT / "logs" / log_name).open("a", encoding="utf-8") if log_name else None
    process = None
    try:
        process = subprocess.Popen([str(PYTHON), "-u", *map(str, arguments)], cwd=PROJECT, env=CHILD_ENV,
                                   stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
        for line in process.stdout:
            print(line, end="", flush=True)
            if log:
                log.write(line)
                log.flush()
        status = process.wait()
        if status:
            raise RuntimeError(f"Experiment command exited with status {status}; inspect the saved log.")
    except BaseException:
        if process is not None and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait()
        raise
    finally:
        if process is not None and process.stdout is not None:
            process.stdout.close()
        if log:
            log.close()

