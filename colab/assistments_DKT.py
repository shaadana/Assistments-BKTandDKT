# termination can bypass it; see the Drive directory and resume instructions.
arguments = ["run_dkt_experiment.py", "--data-2012", LOCAL_INPUTS["2012"],
             "--output", EXPERIMENT, "--cache", CACHE, "--config", CONFIG_PATH]
if RUN_2009:
    arguments += ["--data-2009", LOCAL_INPUTS["2009"]]
if SMOKE_TEST:
    arguments.append("--smoke")
if (EXPERIMENT / "experiment_spec.json").exists():
    arguments.append("--resume")
_run_error = None
try:
    run_python(*arguments, log_name="training.log")
except BaseException as error:
    _run_error = error
    print("Run did not finish:", repr(error))
finally:
    (RUN_ROOT / "notebook_status.json").write_text(json.dumps({
        "status": "failed_or_interrupted" if _run_error else "completed",
        "error": repr(_run_error) if _run_error else None,
        "updated_utc": datetime.now(timezone.utc).isoformat()}, indent=2) + "\n")
    try:
        finalize_and_download()
    except Exception as export_error:
        print("Archive/download step failed:", repr(export_error))
        print("Existing Drive artifacts remain at", RUN_ROOT)
        # A ZIP/disk failure must not suppress an already available HTML report.
        download_saved_outputs(include_archive=False)
        if _run_error is None:
            raise
if _run_error is not None:
    raise _run_error

