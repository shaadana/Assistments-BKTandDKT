def copy_input(year, source):
    destination = LOCAL_DATA / f"assistments{year}.csv"
    temporary = destination.with_suffix(".csv.partial")
    digest = hashlib.sha256()
    copied = 0
    print(f"Copying {year}: {source.stat().st_size / 1e9:.2f} GB", flush=True)
    try:
        with source.open("rb") as incoming, temporary.open("wb") as outgoing:
            for block in iter(lambda: incoming.read(8 * 1024 * 1024), b""):
                outgoing.write(block)
                digest.update(block)
                copied += len(block)
        if copied != source.stat().st_size:
            raise RuntimeError("Source size changed while copying. Run this cell again.")
        temporary.replace(destination)
    finally:
        temporary.unlink(missing_ok=True)
    provenance = {"source_kind": "User CSV copied from mounted Google Drive",
                  "drive_path": str(source), "local_path": str(destination),
                  "csv_sha256": digest.hexdigest(), "size_bytes": copied,
                  "copied_utc": datetime.now(timezone.utc).isoformat(),
                  "note": "Hash records actual supplied bytes; affect-detector provenance is not independently verified."}
    # The training scripts automatically capture this sidecar and check its hash.
    destination.with_name(destination.stem + "_source.json").write_text(json.dumps(provenance, indent=2))
    return destination, provenance

